def is_arabic(text: str) -> bool:
    """Check if the text predominantly contains Arabic characters."""
    if not text:
        return False
    arabic_chars = sum(1 for c in text if '\u0600' <= c <= '\u06FF' or '\u0750' <= c <= '\u077F')
    total_letters = sum(1 for c in text if c.isalpha())
    if total_letters == 0:
        return bool(arabic_chars)
    return (arabic_chars / total_letters) > 0.3
